def katakana_to_hiragana(text: str) -> str:
    """カタカナをひらがなに変換"""
    res = []
    for ch in text:
        code = ord(ch)
        if 0x30A1 <= code <= 0x30F6:
            res.append(chr(code - 0x60))
        else:
            res.append(ch)
    return "".join(res)


def get_japanese_sort_key(name: str):
    """
    日本語ゲームタイトルを五十音順・アルファベット順に自然に並べるためのソートキー。
    1. 【製品版】などの記号タグを徹底除去
    2. 漢字辞書にあればひらがな読みに置換
    3. カタカナをひらがなに統一
    4. グループ順:
       - グループ 0: ひらがな・カタカナ・漢字（五十音順 あ〜ん）
       - グループ 1: アルファベット (A-Z)
       - グループ 2: 数字・記号・その他
    5. 数値を含む場合は自然順（Natural Sort: 2 < 10）
    """
    if not name:
        return (9, [])

    # 1. 記号・装飾タグの除去
    clean = clean_game_name(name)
    clean = re.sub(r'^[^\w\u3040-\u309F\u30A0-\u30FF\u4E00-\u9FFF]+', '', clean)

    # 2. 辞書マッチング（前方一致・部分一致）
    reading = None
    for k, v in TITLE_READINGS.items():
        if clean.startswith(k) or k in clean:
            reading = v
            break

    if not reading:
        reading = clean

    # 3. カタカナ -> ひらがな
    hira = katakana_to_hiragana(reading)

    # 4. 文字グループ判定
    first_char = hira[0] if hira else ''
    if '\u3040' <= first_char <= '\u309F' or '\u4E00' <= first_char <= '\u9FFF':
        group = 0  # 五十音（あ〜ん、漢字）
    elif first_char.isascii() and first_char.isalpha():
        group = 1  # アルファベット (A-Z)
    else:
        group = 2  # 数字・記号

    # 5. 自然順（Natural Sort: 数値部分を int にパース）
    parts = []
    for chunk in re.split(r'(\d+)', hira.lower()):
        if chunk.isdigit():
            parts.append(int(chunk))
        elif chunk:
            parts.append(chunk)

    return (group, parts)

